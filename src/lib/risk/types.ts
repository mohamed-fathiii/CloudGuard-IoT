
/**
 * CloudGuard IoT
 * M4 - Detection & Risk Engine
 *
 * Core domain types for security event processing.
 */

// Supported event sources
export type EventSource =
  | "simulated_iot"
  | "aws"
  | "cloud"
  | "unknown";

// Event severity
// Severity reported by the event source
export type EventSeverity =
  | "low"
  | "medium"
  | "high"
  | "critical";

// Risk level calculated by M4
export type RiskLevel =
  | "low"
  | "medium"
  | "high"
  | "critical";
// Raw event received from the API
export interface RawSecurityEvent {
  sourceType: EventSource;
  sourceId: string;
  eventType: string;
  severity?: EventSeverity;
  description?: string;
  occurredAt: string;
  metadata?: Record<string, unknown>;
}

// Standardized event used internally by M4
export interface NormalizedSecurityEvent {
  eventId?: string;
  sourceType: EventSource;
  sourceId: string;
  eventType: string;
  severity: EventSeverity;
  description: string;
  occurredAt: Date;
  metadata: Record<string, unknown>;
}

// Detection result generated by a rule
export interface DetectionFinding {
  ruleId: string;
  title: string;
  description: string;
  severity: EventSeverity;
  detectedAt: Date;
  eventId?: string;
}

// Final risk assessment
export interface RiskAssessment {
  score: number;
  level: RiskLevel;
  reasons: string[];
  findings: DetectionFinding[];
  assessedAt: Date;
}
